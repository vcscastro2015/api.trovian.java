-- changeset trovian:p0c-07-funcao-criar-particoes splitStatements:false
-- comment: cria particoes mensais adiantadas. Sem particao para a data, o INSERT falha.
CREATE OR REPLACE FUNCTION public.criar_particoes_mensais(
    p_meses_futuros int DEFAULT 3
) RETURNS int
LANGUAGE plpgsql AS $$
DECLARE
    tabelas  constant text[] := ARRAY['transmissao','transmissao_basica','telemetria'];
    t        text;
    i        int;
    inicio   date;
    fim      date;
    nome     text;
    criadas  int := 0;
BEGIN
    FOREACH t IN ARRAY tabelas LOOP
        FOR i IN 0 .. p_meses_futuros LOOP
            inicio := date_trunc('month', current_date)::date + (i || ' month')::interval;
            fim    := (inicio + interval '1 month')::date;
            nome   := format('%s_p%s', t, to_char(inicio, 'YYYYMM'));

            IF to_regclass('public.' || nome) IS NULL THEN
                EXECUTE format(
                    'CREATE TABLE public.%I PARTITION OF public.%I FOR VALUES FROM (%L) TO (%L)',
                    nome, t, inicio, fim
                );
                criadas := criadas + 1;
                RAISE NOTICE 'particao criada: %', nome;
            END IF;
        END LOOP;
    END LOOP;
    RETURN criadas;
END $$;

COMMENT ON FUNCTION public.criar_particoes_mensais IS
    'Cria particoes mensais adiantadas. Agendar diariamente. Sem particao para a data, o INSERT falha.';
