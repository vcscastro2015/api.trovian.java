-- changeset trovian:p0c-08-funcao-expurgo splitStatements:false
-- comment: expurgo por DROP PARTITION e instantaneo. Um DELETE equivalente levaria horas e deixaria bloat.
CREATE OR REPLACE FUNCTION public.expurgar_particoes_antigas(
    p_meses_retencao int DEFAULT 24,
    p_dry_run        boolean DEFAULT true
) RETURNS TABLE (particao text, acao text)
LANGUAGE plpgsql AS $$
DECLARE
    corte date := (date_trunc('month', current_date) - (p_meses_retencao || ' month')::interval)::date;
    r     record;
BEGIN
    FOR r IN
        SELECT c.relname
        FROM   pg_class c
        JOIN   pg_inherits i ON i.inhrelid = c.oid
        JOIN   pg_class p    ON p.oid = i.inhparent
        WHERE  p.relname IN ('transmissao','transmissao_basica','telemetria')
          AND  c.relname ~ '_p[0-9]{6}$'
          AND  to_date(right(c.relname, 6), 'YYYYMM') < corte
        ORDER BY c.relname
    LOOP
        IF p_dry_run THEN
            particao := r.relname; acao := 'SERIA REMOVIDA'; RETURN NEXT;
        ELSE
            EXECUTE format('DROP TABLE public.%I', r.relname);
            particao := r.relname; acao := 'REMOVIDA'; RETURN NEXT;
        END IF;
    END LOOP;
END $$;

COMMENT ON FUNCTION public.expurgar_particoes_antigas IS
    'Expurgo por DROP de particao. Padrao dry_run=true. Ajuste a retencao a politica de LGPD do cliente.';
-- rollback DROP FUNCTION public.expurgar_particoes_antigas(int, boolean);


